/**
 * Markdown output: one file per section (features in features/), linked to each
 * other and to the code. Diagrams are Mermaid, which GitHub and GitLab render.
 */
import { posix } from "node:path";
import { PARTS, type Block, type Inline, type Page, type Part } from "./content.js";

export const GENERATED_MARK = "<!-- Generated by builtlore";

export function renderMarkdown(pages: Page[], opts: { generator: string; repoPrefix: string }): Map<string, string> {
  const anchorPage = new Map<string, string>();
  const pageIds = new Set(pages.map((p) => p.id));
  const collect = (blocks: Block[], file: string) => {
    for (const b of blocks) {
      if (b.t === "h" && b.id) anchorPage.set(b.id, file);
      if (b.t === "details") collect(b.blocks, file);
    }
  };
  for (const p of pages) {
    anchorPage.set(p.id, p.file);
    collect(p.blocks, p.file);
    if (p.group) {
      anchorPage.set(p.group.id, pages.find((x) => x.group?.id === p.group!.id)!.file);
      pageIds.add(p.group.id);
    }
  }
  const out = new Map<string, string>();
  for (const page of pages) {
    const dir = posix.dirname(page.file);
    const depth = dir === "." ? 0 : dir.split("/").length;
    const ctx: Ctx = { dir, anchorPage, pageIds, page, repo: "../".repeat(depth) + opts.repoPrefix };
    const lines: string[] = [
      `${GENERATED_MARK} ${opts.generator.replace(/^builtlore\s*/, "")} from the code and builtlore.edits.yaml. Do not edit this file: run \`builtlore serve\` or edit builtlore.edits.yaml, then \`builtlore docs\`. -->`,
      "",
    ];
    if (page.file !== "README.md") lines.push(`[← ${pages[0].title}](${rel(dir, "README.md")})`, "");
    lines.push(`<a id="${page.id}"></a>`, "", `# ${page.title}`, "");
    if (page.lead) lines.push(`*${text(page.lead)}*`, "");
    for (const b of page.blocks) lines.push(...block(b, ctx), "");
    if (page.file === "README.md") {
      // Same order as the HTML: by part, grouped pages (features) nested under one entry.
      lines.push("## Contents", "");
      let part: Part | null = null;
      let group: string | null = null;
      for (const p of pages.slice(1)) {
        if (p.part !== part) {
          part = p.part;
          lines.push("", `**${PARTS[part].title}** · *${PARTS[part].lead}*`, "");
        }
        if (p.group) {
          if (group !== p.group.id) lines.push(`- ${p.group.title}: ${p.group.lead}`);
          group = p.group.id;
          lines.push(`  - [${p.title}](${rel(dir, p.file)})`);
        } else {
          group = null;
          lines.push(`- [${p.title}](${rel(dir, p.file)})${p.lead ? `: ${text(p.lead)}` : ""}`);
        }
      }
      lines.push("", "Printable version: [index.html](index.html).", "");
    }
    out.set(page.file, lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n");
  }
  return out;
}

interface Ctx {
  dir: string;
  anchorPage: Map<string, string>;
  pageIds: Set<string>;
  page: Page;
  /** Path from this page to the repository root. */
  repo: string;
}

function rel(fromDir: string, file: string): string {
  const r = posix.relative(fromDir === "." ? "" : fromDir, file);
  return r || file;
}

function block(b: Block, ctx: Ctx): string[] {
  switch (b.t) {
    case "h":
      return [...(b.id ? [`<a id="${b.id}"></a>`, ""] : []), `${"#".repeat(b.level)} ${b.text}`];
    case "p":
      return [inline(b.c, ctx)];
    case "note":
      return [`> ${b.kind === "warn" ? "**Note:** " : ""}${inline(b.c, ctx)}`];
    case "list":
      return b.items.map((it) => `- ${inline(it, ctx)}`);
    case "steps":
      return b.items.map((it, i) => `${i + 1}. ${inline(it, ctx)}`);
    case "details": {
      // GitHub and GitLab render <details>; Markdown inside needs blank lines around it.
      const inner = b.blocks.flatMap((x) => [...block(x, ctx), ""]);
      return ["<details>", `<summary>${b.summary.replace(/[<>&]/g, "")}</summary>`, "", ...inner, "</details>"];
    }
    case "table": {
      if (!b.rows.length) return [];
      const head = `| ${b.head.map((h) => cell(h)).join(" | ")} |`;
      const sep = `| ${b.head.map(() => "---").join(" | ")} |`;
      return [head, sep, ...b.rows.map((r) => `| ${r.map((c) => cell(inline(c, ctx))).join(" | ")} |`)];
    }
    case "diagram":
      return ["```mermaid", b.mermaid, "```"];
    case "mermaid":
      return ["```mermaid", b.code, "```"];
    case "canvas":
      return [`[Open the canvas](${b.href}): every page, form and step, interactive.`];
  }
}

function cell(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>") || " ";
}

function text(s: string): string {
  // Keep the text as written; only stop Markdown from reading it as markup.
  // Underscores inside words (purchase_request) are not emphasis in GFM, so they stay readable.
  return s.replace(/([\\`*[\]<>])/g, "\\$1").replace(/(^|[^A-Za-z0-9])_|_(?=$|[^A-Za-z0-9])/g, (m) => m.replace("_", "\\_"));
}

function codeSpan(s: string): string {
  const ticks = s.includes("`") ? "``" : "`";
  return `${ticks}${ticks.length > 1 ? " " : ""}${s}${ticks.length > 1 ? " " : ""}${ticks}`;
}

function inline(parts: Inline[], ctx: Ctx): string {
  return parts
    .map((p) => {
      if (typeof p === "string") return text(p);
      if ("code" in p) return codeSpan(p.code);
      if ("b" in p) return `**${text(p.b)}**`;
      if ("i" in p) return `*${text(p.i)}*`;
      if ("link" in p) {
        const file = ctx.anchorPage.get(p.to);
        const href = !file || file === ctx.page.file ? `#${p.to}` : `${rel(ctx.dir, file)}${ctx.pageIds.has(p.to) ? "" : `#${p.to}`}`;
        return `[${text(p.link)}](${href})`;
      }
      if ("src" in p) {
        const label = p.src.line ? `${p.src.file}:${p.src.line}` : p.src.file;
        const href = `${ctx.repo}${p.src.file}${p.src.line ? `#L${p.src.line}` : ""}`.replace(/ /g, "%20");
        return `[${codeSpan(label)}](${href})`;
      }
      if (p.kind === "role") return "●";
      return `*(${text(p.badge)})*`;
    })
    .join("");
}
